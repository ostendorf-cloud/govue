// Renders a solved palette into a CSS file structurally identical to
// sample.css: a :root[data-theme='<name>'] block, one --color-* line per
// role in the same order base.css declares them, plus the two --shadow-*
// lines.

import { hexToRgb } from './color.ts'
import type { HexPalette, Ink } from './palette.ts'

// The role order base.css and every shipped example theme use. Kept as an
// explicit list rather than derived from a Palette's own key order, so a
// theme always reads in the same order no matter how the generator built it.
const ROLE_ORDER: string[] = [
  'bg',
  'bg-subtle',
  'surface',
  'surface-hover',
  'border',
  'border-strong',
  'text',
  'text-muted',
  'text-faint',
  'accent',
  'accent-text',
  'accent-strong',
  'accent-strong-hover',
  'accent-on',
  'accent-subtle',
  'focus',
  'success-text',
  'success-subtle',
  'warning-text',
  'warning-subtle',
  'danger-text',
  'danger-subtle',
  'danger-strong',
  'danger-strong-hover',
  'danger-on',
  'info-text',
  'info-subtle',
]

/** rgbTriplet renders a hex colour as the "r g b" form the alpha-carrying
 *  rgb() tokens use, matching base.css's own shadow and overlay lines. */
function rgbTriplet(hex: string): string {
  const { r, g, b } = hexToRgb(hex)
  return `${Math.round(r)} ${Math.round(g)} ${Math.round(b)}`
}

export interface RenderInput {
  name: string
  light: HexPalette
  dark: HexPalette
  ink: Ink
}

/** renderTheme writes the CSS string for one generated theme. The header
 *  states plainly that this file is an example the generator produced and
 *  that a real theme belongs in the consumer's own repository, not in
 *  govue: the generator's code is public, a consumer's seeds and output
 *  are not committed here. */
export function renderTheme({ name, light, dark, ink }: RenderInput): string {
  const lines = ROLE_ORDER.map(
    (key) => `  --color-${key}: light-dark(${light[key]}, ${dark[key]});`,
  )

  const lightInk = rgbTriplet(ink.light)
  const darkInk = rgbTriplet(ink.dark)

  const overlay = `  --color-overlay: light-dark(rgb(${lightInk} / 0.45), rgb(${darkInk} / 0.68));`
  const shadowCard = `  --shadow-card: 0 1px 2px light-dark(rgb(${lightInk} / 0.07), rgb(0 0 0 / 0.52));`
  const shadowDialog = [
    '  --shadow-dialog:',
    `    0 10px 30px -12px light-dark(rgb(${lightInk} / 0.26), rgb(0 0 0 / 0.78)),`,
    `    0 2px 6px light-dark(rgb(${lightInk} / 0.09), rgb(0 0 0 / 0.52));`,
  ].join('\n')

  return [
    '/*',
    ` * ${name}: generated by govue's theme generator.`,
    ' *',
    ' * This is an example theme produced from a seed configuration, not meant',
    ' * to be committed to govue: a real theme belongs in the repository that',
    ' * consumes this package, filling the same contract as base.css.',
    ' */',
    '',
    `:root[data-theme='${name}'] {`,
    lines.slice(0, 4).join('\n'),
    overlay,
    '',
    lines.slice(4, 6).join('\n'),
    '',
    lines.slice(6, 9).join('\n'),
    '',
    lines.slice(9, 16).join('\n'),
    '',
    lines.slice(16, 27).join('\n'),
    '',
    shadowCard,
    shadowDialog,
    '}',
    '',
  ].join('\n')
}
